import { ImageProvider, GenerationOptions, GenerationResult } from '../types';
import { ComfyUIClient } from './comfyui-client';
import { buildWorkflow, generateSeed } from './workflow-builder';
import { db } from '@/lib/db';
import { generations, images } from '@/lib/db/schema';
import { eq } from 'drizzle-orm';
import { writeFile, mkdir } from 'fs/promises';
import { join } from 'path';

export class ComfyUIProvider implements ImageProvider {
  name: 'comfyui' = 'comfyui';
  private client: ComfyUIClient;

  constructor() {
    this.client = new ComfyUIClient();
  }

  async testConnection(): Promise<boolean> {
    return this.client.testConnection();
  }

  async generateImage(options: GenerationOptions): Promise<GenerationResult> {
    const { prompt, batchId, generationId, parameters = {} } = options;

    // Update generation to running
    await db.update(generations)
      .set({ status: 'running' })
      .where(eq(generations.id, generationId));

    try {
      // Generate seed
      const seed = generateSeed();

      // Build workflow with parameters
      const workflowParams = {
        prompt,
        seed,
        ...parameters,
      };

      const workflow = await buildWorkflow('txt2img', workflowParams);

      // Submit to ComfyUI
      const { prompt_id } = await this.client.submitPrompt(workflow);

      // Wait for completion
      await this.client.waitForExecution(prompt_id);

      // Download images
      const downloadedImages = await this.client.downloadOutputImages(prompt_id);

      if (downloadedImages.length === 0) {
        throw new Error('No images generated by ComfyUI');
      }

      // Save images to local storage
      const outputDir = join(process.cwd(), process.env.OUTPUT_DIR || '../image-gen/outputs', batchId);
      await mkdir(outputDir, { recursive: true });

      const savedImages = [];
      for (const { buffer, filename, contentType } of downloadedImages) {
        const filePath = join(outputDir, `${generationId}_${filename}`);
        await writeFile(filePath, buffer);

        const [imageRecord] = await db.insert(images).values({
          generationId,
          filePath,
          fileName: filename,
          mediaType: contentType,
          fileSize: buffer.length,
          metadata: { prompt, runNumber: options.runNumber, seed },
        }).returning();

        savedImages.push(imageRecord);
      }

      // Update generation with success
      await db.update(generations)
        .set({
          status: 'success',
          metadata: {
            provider: 'comfyui',
            workflowType: 'txt2img',
            promptId: prompt_id,
            seed,
            parameters: workflowParams,
          },
          completedAt: new Date(),
        })
        .where(eq(generations.id, generationId));

      return {
        generationId,
        images: savedImages.map(img => ({
          id: img.id,
          filePath: img.filePath,
          fileName: img.fileName,
          mediaType: img.mediaType,
          fileSize: img.fileSize,
        })),
        metadata: { provider: 'comfyui', seed, promptId: prompt_id },
      };

    } catch (error) {
      await db.update(generations)
        .set({
          status: 'failed',
          error: error instanceof Error ? error.message : 'Unknown error',
          completedAt: new Date(),
        })
        .where(eq(generations.id, generationId));

      throw error;
    }
  }
}
