import { ImageProvider, GenerationOptions, GenerationResult } from '../types';
import { db } from '@/lib/db';
import { generations, images } from '@/lib/db/schema';
import { eq } from 'drizzle-orm';
import { saveImage } from '@/lib/storage/local-storage';

import { RESOLUTION_PRESETS, DEFAULT_RESOLUTION } from '@/lib/config/resolution-presets';

export class Gemini3Provider implements ImageProvider {
  name: 'gemini3' = 'gemini3';

  private getApiKey(): string {
    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      throw new Error('GEMINI_API_KEY environment variable is not set');
    }
    return apiKey;
  }

  async testConnection(): Promise<boolean> {
    try {
      const apiKey = this.getApiKey();
      const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/gemini-3-pro-image-preview?key=${apiKey}`;

      const response = await fetch(endpoint);
      return response.ok;
    } catch (error) {
      console.error('Gemini 3 connection test failed:', error);
      return false;
    }
  }

  async generateImage(options: GenerationOptions): Promise<GenerationResult> {
    const { prompt, batchId, generationId, parameters = {} } = options;

    // Update generation to running
    await db.update(generations)
      .set({ status: 'running' })
      .where(eq(generations.id, generationId));

    try {
      const apiKey = this.getApiKey();
      const model = 'gemini-3-pro-image-preview';
      const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;

      // Map resolution presets to Gemini 3 imageSize and aspectRatio
      const resolutionId = parameters.resolution || DEFAULT_RESOLUTION;
      const preset = RESOLUTION_PRESETS.find(p => p.id === resolutionId);

      const imageSize = preset?.geminiImageSize || '1K';
      const aspectRatio = preset?.aspectRatio || '1:1';

      const body = {
        contents: [
          {
            role: 'user',
            parts: [{ text: prompt }]
          }
        ],
        generationConfig: {
          responseModalities: ['TEXT', 'IMAGE'],
          imageConfig: {
            aspectRatio: aspectRatio,
            imageSize: imageSize
          }
        }
      };

      const response = await fetch(endpoint, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
        },
        body: JSON.stringify(body),
      });

      if (!response.ok) {
        const errorData = await response.json().catch(() => ({}));
        throw new Error(`Gemini 3 API request failed: ${errorData.error?.message || response.statusText}`);
      }

      const result = await response.json();

      if (!result.candidates || result.candidates.length === 0) {
        throw new Error('No candidates in Gemini 3 response');
      }

      const candidate = result.candidates[0];
      const parts = candidate.content?.parts || [];

      const imageParts = parts.filter((part: any) => part.inlineData && part.inlineData.data);
      const textParts = parts.filter((part: any) => part.text).map((part: any) => part.text);

      if (imageParts.length === 0) {
        // Check for safety filters
        if (candidate.finishReason === 'SAFETY') {
          throw new Error('Image generation blocked by safety filters');
        }
        throw new Error('No images generated by Gemini 3');
      }

      // Save images
      const savedImages = [];
      for (const part of imageParts) {
        const base64Data = part.inlineData.data;
        const mediaType = part.inlineData.mimeType || 'image/png';
        const buffer = Buffer.from(base64Data, 'base64');
        const uint8Array = new Uint8Array(buffer);

        const filePath = await saveImage(
          { uint8Array, mediaType },
          batchId,
          generationId
        );

        const [imageRecord] = await db.insert(images).values({
          generationId,
          filePath,
          fileName: filePath.split('/').pop() || 'unknown',
          mediaType,
          fileSize: uint8Array.length,
          metadata: {
            prompt,
            runNumber: options.runNumber,
            thoughtSignature: part.thoughtSignature
          },
        }).returning();

        savedImages.push(imageRecord);
      }

      // Update generation with success
      await db.update(generations)
        .set({
          status: 'success',
          metadata: {
            provider: 'gemini3',
            text: textParts.join('\n'),
            finishReason: candidate.finishReason,
            imageCount: imageParts.length,
          },
          completedAt: new Date(),
        })
        .where(eq(generations.id, generationId));

      return {
        generationId,
        images: savedImages.map(img => ({
          id: img.id,
          filePath: img.filePath,
          fileName: img.fileName,
          mediaType: img.mediaType,
          fileSize: img.fileSize || undefined,
        })),
        metadata: { provider: 'gemini3', imageCount: imageParts.length },
      };

    } catch (error) {
      console.error('Gemini 3 generation failed:', error);
      await db.update(generations)
        .set({
          status: 'failed',
          error: error instanceof Error ? error.message : 'Unknown error',
          completedAt: new Date(),
        })
        .where(eq(generations.id, generationId));

      throw error;
    }
  }
}
